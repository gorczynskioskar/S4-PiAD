import numpy as np
import matplotlib.pyplot as plt
import sklearn as sk
from sklearn.neighbors import KDTree

class KNN:
    def __init__(self, n_neighbors=1, use_KDTree=False):
        self.n_neighbors = n_neighbors
        self.use_KDTree = use_KDTree

    def fit(self, X, y):
        self.X = X
        self.y = y
        if self.use_KDTree:
            self.tree = KDTree(X)


    def predict(self, X):
        y_pred = []
        is_classification = np.issubdtype(self.y.dtype, np.integer)

        for x in X:

            if self.use_KDTree:
                            dist, ind = self.tree.query(x.reshape(1, -1), k=self.n_neighbors)
                            labels = self.y[ind[0]]

            distances = []

            # liczenie odległości
            for i in range(len(self.X)):
                d = np.linalg.norm(x - self.X[i])
                distances.append((d, self.y[i]))

            # sortowanie po dystansie
            distances.sort(key=lambda x: x[0])

            # wybór k sąsiadów
            neighbors = distances[:self.n_neighbors]
            labels = [neighbor[1] for neighbor in neighbors]

            # klasyfikacja
            if is_classification:
                pred = np.bincount(labels).argmax()
            # regresja
            else:
                pred = np.mean(labels)

            y_pred.append(pred)

        return np.array(y_pred)

    def score(self, X, y):
        y_pred = self.predict(X)

        # klasyfikacja
        if np.issubdtype(y.dtype, np.integer):
            return np.mean(y_pred == y)
        # regresja
        else:
            return np.mean((y_pred - y) ** 2)

