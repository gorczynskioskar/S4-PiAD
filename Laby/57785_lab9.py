import time

sizes = [100, 500, 1000, 2000]

times_brute = []
times_tree = []

for n in sizes:
    X, y = datasets.make_classification(
        n_samples=n,
        n_features=2,
        n_informative=2,
        n_redundant=0,
        random_state=42
    )

    knn_brute = KNN(n_neighbors=5, use_KDTree=False)
    knn_tree = KNN(n_neighbors=5, use_KDTree=True)

    knn_brute.fit(X, y)
    knn_tree.fit(X, y)

    # brute
    start = time.time()
    knn_brute.predict(X)
    times_brute.append(time.time() - start)

    # KDTree
    start = time.time()
    knn_tree.predict(X)
    times_tree.append(time.time() - start)

# wykres
plt.figure(figsize=(7,5))

plt.plot(sizes, times_brute, marker='o', label='Brute force')
plt.plot(sizes, times_tree, marker='o', label='KDTree')

plt.xlabel('Liczba próbek (n)')
plt.ylabel('Czas [s]')
plt.title('Porównanie czasu działania KNN')
plt.legend()
plt.grid(True)
plt.show()

# Dla małych zbiorów różnica czasu działania między metodami jest niewielka,
# jednak dla większych zbiorów KDTree zaczyna znacząco przyspieszać
# wyszukiwanie sąsiadów, ograniczając liczbę sprawdzanych punktów.
